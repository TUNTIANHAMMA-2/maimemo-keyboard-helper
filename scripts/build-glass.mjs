import { build } from 'esbuild';
import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
await build({
  absWorkingDir: root,
  entryPoints: ['ui/liquid-glass-entry.js'],
  outfile: 'content/liquid-glass.js',
  bundle: true,
  minify: true,
  format: 'iife',
  platform: 'browser',
  target: ['firefox109', 'chrome120'],
  define: { 'process.env.NODE_ENV': '"production"' },
  legalComments: 'eof',
  banner: { js: '/* Generated by npm run build:glass. Source: ui/liquid-glass-entry.js */' }
});
const notices = [];
for (const name of ['liquid-glass-react', 'react', 'react-dom', 'scheduler']) {
  const pkg = JSON.parse(await readFile(resolve(root, 'node_modules', name, 'package.json'), 'utf8'));
  notices.push(`${name} ${pkg.version}\n${await readFile(resolve(root, 'node_modules', name, 'LICENSE'), 'utf8')}`);
}
await writeFile(resolve(root, 'docs/third-party-licenses.txt'), notices.join('\n\n====================\n\n'));
console.log('Liquid Glass bundle and third-party license notices generated.');
